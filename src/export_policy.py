"""
Export of a trained Stable-Baselines3 agent to MATLAB (rl_controller.m, EINT_RL_eval.m).

    DO NOT EDIT THIS FILE.

    export_for_matlab(agent, env)

agent: SAC, TD3 or PPO with "MlpPolicy".
env:   your environment, without noise. reset() and step() must return the
       measurements of the drone in info["m"], a dict {t, z, vz, az_prev, z_ref, u_prev} (az_prev and
       u_prev: acceleration and command of the previous step), from which the observation is computed.

Writes policy.mat (the actor, run by rl_controller.m) and traj_model.mat (the mission flown on your model:
EINT_RL_eval.m replays it through rl_controller.m to check your mission() and observation()).
"""

import numpy as np
import torch.nn as nn
from scipy.io import savemat

N_STEPS = 200      # the mission: 10 s at Ts = 0.05 s
MEASUREMENTS = ("t", "z", "vz", "az_prev", "z_ref", "u_prev")


def _layers(modules):
    layers = []
    for mod in modules:
        if isinstance(mod, nn.Linear):
            layers.append([mod.weight.detach().cpu().double().numpy(),
                           mod.bias.detach().cpu().double().numpy(), "none"])
        elif isinstance(mod, (nn.ReLU, nn.Tanh)):
            layers[-1][2] = "relu" if isinstance(mod, nn.ReLU) else "tanh"
        elif not isinstance(mod, (nn.Flatten, nn.Identity)):
            raise ValueError(f"layer not handled by the export: {mod}")
    return layers


def _policy_matrices(agent):
    name = type(agent).__name__
    if name == "SAC":
        layers, output = _layers(agent.actor.latent_pi) + _layers([agent.actor.mu]), "tanh_scale"
    elif name == "TD3":
        layers, output = _layers(agent.actor.mu), "scale"
    elif name == "PPO":
        layers = _layers(agent.policy.mlp_extractor.policy_net) + _layers([agent.policy.action_net])
        output = "clip"
    else:
        raise ValueError(f"the export handles SAC, TD3 and PPO, not {name}")
    P = {"n_layers": len(layers), "activations": ",".join(a for _, _, a in layers), "output": output,
         "action_low": agent.action_space.low.astype(np.float64),
         "action_high": agent.action_space.high.astype(np.float64)}
    for i, (W, b, _) in enumerate(layers, start=1):
        P[f"W{i}"], P[f"b{i}"] = W, b.reshape(-1, 1)
    return P


def export_for_matlab(agent, env):
    savemat("policy.mat", _policy_matrices(agent))
    obs, info = env.reset(seed=0)
    log = {k: [] for k in (*MEASUREMENTS, "obs", "u")}
    for _ in range(N_STEPS):
        u = float(np.asarray(agent.predict(obs, deterministic=True)[0]).reshape(-1)[0])
        for k in MEASUREMENTS:
            log[k].append(float(info["m"][k]))
        log["obs"].append(np.asarray(obs, dtype=np.float64).reshape(-1))
        log["u"].append(u)
        obs, _, terminated, truncated, info = env.step(np.array([u], dtype=np.float32))
        if terminated or truncated:
            break
    traj = {k: np.array(v) for k, v in log.items()}
    savemat("traj_model.mat", {**{k: traj[k].reshape(-1, 1) for k in (*MEASUREMENTS, "u")}, "obs": traj["obs"]})
    print(f"policy.mat and traj_model.mat written ({len(traj['t'])} steps): now run EINT_RL_eval in MATLAB.")
